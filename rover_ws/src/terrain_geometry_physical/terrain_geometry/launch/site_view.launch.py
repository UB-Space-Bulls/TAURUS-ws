"""Inspect an evaluated MDRS patch in RViz, independently of rover navigation."""
import math
from pathlib import Path

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import (
    DeclareLaunchArgument, EmitEvent, LogInfo, OpaqueFunction,
    SetEnvironmentVariable, TimerAction)
from launch.events import Shutdown
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node
import yaml


def setup(context):
    def value(name):
        return LaunchConfiguration(name).perform(context)
    config = Path(value('config')).expanduser().resolve()
    if not config.is_file():
        raise ValueError(f'Patch config does not exist: {config}. Run evaluate_patch.py first.')
    document = yaml.safe_load(config.read_text())
    try:
        patch = document['mdrs_patch_publisher']['ros__parameters']
        terrain = document['terrain_geometry']['ros__parameters']
        frame = str(patch['frame'])
        center = [float(patch['center_x']), float(patch['center_y']),
                  float(terrain['seed_height'])]
        data = Path(patch['data']).expanduser()
        if not data.is_absolute():
            data = config.parent / data
    except (KeyError, TypeError, ValueError) as exc:
        raise ValueError('Expected the patch.yaml generated by evaluate_patch.py') from exc
    if not frame or terrain.get('target_frame') != frame:
        raise ValueError('Patch frame and terrain target_frame must match')
    if frame == 'mdrs_patch_origin':
        raise ValueError('Patch frame must be distinct from the viewer frame mdrs_patch_origin')
    if not all(math.isfinite(number) for number in center):
        raise ValueError('Patch center and seed height must be finite')
    if not data.is_file():
        raise ValueError(f'MDRS point data does not exist: {data}')
    rate = float(value('processing_rate'))
    duration = float(value('test_duration'))
    if not math.isfinite(rate) or rate <= 0:
        raise ValueError('processing_rate must be finite and positive')
    if not math.isfinite(duration) or duration < 0:
        raise ValueError('test_duration must be finite and nonnegative')

    actions = [
        # Use the ROS/system Python packages rather than user-site NumPy installs.
        SetEnvironmentVariable('PYTHONNOUSERSITE', '1'),
        LogInfo(msg=f'MDRS patch center: ({center[0]:g}, {center[1]:g}); '
                    f'frame={frame}; processing={rate:g} Hz. '
                    'This launch runs continuously until Ctrl+C or test_duration.'),
        Node(package='terrain_geometry', executable='site_patch_publisher',
             name='mdrs_patch_publisher', output='screen', parameters=[str(config), {
                 'data': str(data.resolve()), 'use_sim_time': False}]),
        Node(package='terrain_geometry', executable='terrain_node',
             name='terrain_geometry', output='screen', parameters=[str(config), {
                 'processing_rate': rate, 'use_sim_time': False,
                 'input_topic': '/mdrs/map_patch', 'target_frame': frame,
                 'rolling_window': False}]),
        # A defined local origin for the selected map patch, not a rover pose.
        Node(package='tf2_ros', executable='static_transform_publisher',
             name='mdrs_patch_view_origin', output='screen', arguments=[
                 '--x', str(center[0]), '--y', str(center[1]), '--z', str(center[2]),
                 '--frame-id', frame, '--child-frame-id', 'mdrs_patch_origin'],
             parameters=[{'use_sim_time': False}]),
    ]
    if value('rviz') == 'true':
        share = Path(get_package_share_directory('terrain_geometry'))
        actions.append(Node(package='rviz2', executable='rviz2', name='mdrs_rviz',
                            output='screen', arguments=[
                                '-d', str(share / 'config/mdrs_site.rviz'), '-f', frame],
                            parameters=[{'use_sim_time': False}]))
    if duration > 0:
        actions.append(TimerAction(period=duration, actions=[
            LogInfo(msg='MDRS test duration reached; shutting down.'),
            EmitEvent(event=Shutdown(reason='MDRS test duration reached'))]))
    return actions


def generate_launch_description():
    return LaunchDescription([
        DeclareLaunchArgument('config', default_value=str(
            Path.home() / 'mdrs_site/my_patch/patch.yaml'),
            description='The patch.yaml generated by evaluate_patch.py'),
        DeclareLaunchArgument('rviz', default_value='true', choices=['true', 'false']),
        DeclareLaunchArgument('processing_rate', default_value='1.0'),
        DeclareLaunchArgument('test_duration', default_value='0.0',
                              description='Wall seconds before shutdown; 0 runs until Ctrl+C'),
        OpaqueFunction(function=setup),
    ])
